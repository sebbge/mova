"""Generates src/lib/landing/departments.ts from the limits in lib/transit/migrations/0002_areas.sql.

Shared borders are simplified once and both departments use the same result, so neighbours
leave no gaps between them. Usage: python scripts/departments.py
"""

import collections
import math
import re
from pathlib import Path

WEB = Path(__file__).resolve().parents[1]
SQL = WEB.parents[1] / "lib/transit/migrations/0002_areas.sql"
OUT = WEB / "src/lib/landing/departments.ts"

TOLERANCE = 0.012
MIN_AREA = 0.002
LAT0 = math.radians(-32.6)
WEST, SOUTH, EAST, NORTH = -58.5, -35.05, -53.05, -30.05
SCALE = 100


def parse(sql):
    for code, wkt in re.findall(r"\('(uy-[a-z]{2})', '[^']+', ST_GeomFromText\('([^']+)'", sql):
        polys = re.findall(r"\(\(([^()]+(?:\),\([^()]+)*)\)\)", wkt) if wkt.startswith("MULTI") else [wkt[9:-2]]
        yield code, [
            [[tuple(map(float, p.split())) for p in ring.split(",")] for ring in poly.split("),(")] for poly in polys
        ]


def douglas_peucker(pts):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        i, j = stack.pop()
        (x1, y1), (x2, y2) = pts[i], pts[j]
        dx, dy = x2 - x1, y2 - y1
        length = math.hypot(dx, dy)
        best, idx = -1.0, -1
        for k in range(i + 1, j):
            x, y = pts[k]
            d = abs(dy * (x - x1) - dx * (y - y1)) / length if length else math.hypot(x - x1, y - y1)
            if d > best:
                best, idx = d, k
        if best > TOLERANCE:
            keep[idx] = True
            stack += [(i, idx), (idx, j)]
    return [p for p, k in zip(pts, keep) if k]


def main():
    areas = dict(parse(SQL.read_text(encoding="utf-8")))

    neighbours = collections.defaultdict(set)
    for polys in areas.values():
        for ring in (r for poly in polys for r in poly):
            for a, b in zip(ring, ring[1:]):
                if a != b:
                    neighbours[a].add(b)
                    neighbours[b].add(a)
    nodes = {v for v, n in neighbours.items() if len(n) > 2}

    arcs = {}

    def arc(pts):
        key = tuple(pts)
        if key[::-1] in arcs:
            return arcs[key[::-1]][::-1]
        return arcs.setdefault(key, douglas_peucker(pts))

    def ring(pts):
        pts = pts[:-1] if pts[0] == pts[-1] else pts
        cuts = [i for i, p in enumerate(pts) if p in nodes]
        if not cuts:
            far = max(range(len(pts)), key=lambda i: math.dist(pts[i], pts[0]))
            out = douglas_peucker(pts[: far + 1])[:-1] + douglas_peucker(pts[far:] + [pts[0]])[:-1]
        else:
            rotated = pts[cuts[0] :] + pts[: cuts[0]] + [pts[cuts[0]]]
            cuts = [i for i, p in enumerate(rotated) if p in nodes]
            out = [p for a, b in zip(cuts, cuts[1:]) for p in arc(rotated[a : b + 1])[:-1]]
        return out if len(out) >= 3 and area(out) >= MIN_AREA else None

    def area(r):
        return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(r, r[1:] + r[:1]))) / 2

    def point(p):
        x = (p[0] - WEST) * math.cos(LAT0) * SCALE
        y = (NORTH - p[1]) * SCALE
        return f"{x:.1f} {y:.1f}".replace(".0 ", " ").removesuffix(".0")

    paths = {}
    for code, polys in sorted(areas.items()):
        rings = [r for poly in polys if ring(poly[0]) for r in map(ring, poly) if r]
        paths[code] = "".join("M" + "L".join(map(point, r)) + "Z" for r in rings)

    width = round((EAST - WEST) * math.cos(LAT0) * SCALE)
    height = round((NORTH - SOUTH) * SCALE)
    entries = "\n".join(f"  '{code}': '{d}'," for code, d in paths.items())
    OUT.write_text(
        "// generated by scripts/departments.py: do not edit by hand\n"
        f"export const DEPARTMENTS_VIEWBOX = '0 0 {width} {height}';\n\n"
        f"export const DEPARTMENT_PATHS: Record<string, string> = {{\n{entries}\n}};\n",
        encoding="utf-8",
    )
    print(f"{OUT.name}: {len(paths)} departments, {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
